import { strict as assert } from "node:assert";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

/**
 * The pen path under the loader is generated from the artwork, and the failure
 * it guards against is quiet: someone edits DRAWING_D or SUN_D in Mark.tsx, the
 * build stays green, and the loader draws last week's cactus inside this week's
 * clip. The generator is deterministic, so running it in --check mode is the
 * whole test.
 */
test("the committed centreline still matches the artwork in Mark.tsx", () => {
  const out = execFileSync("node", ["scripts/mark-centerline.mjs", "--check"], {
    cwd: ROOT,
    encoding: "utf8",
  });
  assert.match(out, /matches the artwork/);
});

test("the generated module carries its measurements, so a reviewer can see them", () => {
  const text = readFileSync(join(ROOT, "components/site/markCenterline.ts"), "utf8");
  assert.match(text, /GENERATED by scripts\/mark-centerline\.mjs/);
  assert.match(text, /ink reach from the pen path\s+\d/);
  assert.match(text, /ink revealed ahead of the pen\s+\d/);
  /* The brush has to be wider than the ink is thick, or the finished draw is
     not the mark. The generator asserts it; this checks the number it wrote. */
  const reach = Number(/ink reach from the pen path\s+([\d.]+)/.exec(text)[1]);
  const brush = Number(/export const MARK_BRUSH = (\d+)/.exec(text)[1]);
  assert.ok(brush >= reach * 2, `brush ${brush} does not cover a reach of ${reach}`);
});
